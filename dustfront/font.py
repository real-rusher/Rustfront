_TRANS = {"\u00e4": "\u00c4", "\u00f6": "\u00d6", "\u00fc": "\u00dc", "\u00df": "SS"}


class Schrift:
    def __init__(self) -> None:
        self._rows = {k: v.split("/") for k, v in _G.items()}
        self._cache: dict[tuple, pygame.Surface] = {}

    @staticmethod
    def vorbereiten(text: str) -> str:
        return "".join(_TRANS.get(c, c.upper() if c.isalpha() else c) for c in text)

    def breite(self, text: str, skala=1, abstand=1) -> int:
        n = len(self.vorbereiten(text))
        return 0 if n == 0 else n * (GW + abstand) * skala - abstand * skala

    def flaeche(self, text: str, farbe, skala=1, abstand=1) -> pygame.Surface:
        key = (text, farbe, skala, abstand)
        hit = self._cache.get(key)
        if hit is not None:
            return hit
        t = self.vorbereiten(text)
        s = pygame.Surface((max(1, self.breite(text, skala, abstand)), GH * skala),
                           pygame.SRCALPHA)
        schritt = (GW + abstand) * skala
        for i, ch in enumerate(t):
            rows = self._rows.get(ch) or self._rows["?"]
            for ry, row in enumerate(rows):
                lauf = 0
                for rx in range(GW + 1):
                    an = rx < GW and row[rx] == "1"
                    if an:
                        lauf += 1
                    elif lauf:
                        pygame.draw.rect(s, farbe, (i * schritt + (rx - lauf) * skala,
                                                    ry * skala, lauf * skala, skala))
                        lauf = 0
        if len(self._cache) > 700:
            self._cache.clear()
        self._cache[key] = s
        return s

    def zeichnen(self, ziel, text, x, y, farbe, skala=1, abstand=1, ausrichtung="links",
                 schatten=None):
        s = self.flaeche(text, farbe, skala, abstand)
        if ausrichtung == "rechts":
            x -= s.get_width()
        elif ausrichtung == "mitte":
            x -= s.get_width() // 2
        if schatten is not None:
            ziel.blit(self.flaeche(text, schatten, skala, abstand), (x + skala, y + skala))
        ziel.blit(s, (x, y))
        return s.get_width()


